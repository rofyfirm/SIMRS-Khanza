    private String derajat(int total) {
        if(total<=30){
            return "Tidak Sakit";
        }else if(total<=60){
            return "Minimal/Patologi Diragukan";
        }else if(total<=90){
            return "Sakit Ringan";
        }else if(total<=120){
            return "Sakit Sedang";
        }else if(total<=150){
            return "Sakit Agak Berat";
        }else if(total<=180){
            return "Sakit Berat";
        }else{
            return "Sakit Sangat Berat";
        }
    }

